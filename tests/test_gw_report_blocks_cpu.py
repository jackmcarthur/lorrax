def test_stage_rows():
    from gw.gw_config import HeadCorrection
    assert pr.w_roles_detail([("static", 0j), ("probe", 2j)], n_q=9, trs_allowed=False) == \
        "static (omega 0), probe (omega 27.2i eV, ordered orientations); Dyson on 9 q"
    assert pr.w_roles_detail([("static", 0j)], n_q=4) == "static (omega 0); Dyson on 4 q"
    assert pr.v_q_detail(n_q=9, n_mu=6, seconds=0.587) == "9 q, 6 x 6 per q, 0.59 s"
    assert pr.v_q_detail(n_q=9, n_mu=6, seconds=None,
                         restart_file="/r/tmp/isdf_tensors_6.h5") == \
        "9 q, 6 x 6 per q, read from isdf_tensors_6.h5"
    head = lambda value: NS(head=NS(correction=HeadCorrection(value), wcoul0_source="s_tensor"))
    assert pr.head_detail(head("full")) == "full, local fields, from dipole.h5"
    assert pr.head_detail(head("off")) == "off: no q->0 cell term"


def test_sigma_window_rows_name_a_reused_rule_without_its_digest():
    window = dict(name="w<E_F cond:omega_tail", kind="sign_definite_negative",
                  box_ry=[-0.75, -0.14, 0.0184, 0.0184], node_count=5, sup_error=7.6e-6,
                  eps=1e-4, kappa_max=1.0, rule_source="plan:50d38143a80c4304")
    head, rows = pr.sigma_rule_detail_lines(dict(
        eta_ry=0.0184, eps=1e-4, n_windows=1, window_tau_pairs=5, distinct_tau_count=5,
        branches=[dict(windows=[window])]))
    assert head == "eta 0.25 eV, eps 1.0e-04; 1 window, 5 (window, tau) pairs, 5 distinct tau"
    assert rows[0].split() == ["window", "kind", "Re", "d", "/", "eta", "nodes", "sup/eps",
                               "kappa", "rule"]
    assert rows[1].endswith("   reused") and "50d38143" not in rows[1]
