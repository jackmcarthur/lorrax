"""Head-excluded W densification — the coarse→fine head channel (C1).

WHY THIS MODULE EXISTS
----------------------
BerkeleyGW never interpolates a divergent object.  ``kernel.x`` writes a
divergence-STRIPPED head, wing and body to ``bsemat.h5``
(``mtxel_kernel.f90:525-556``; for a semiconductor the head is stored as
literally ``1.0``) and ``intkernel`` restores the singular factors at
assembly time, per fine q (``intkernel.f90:1103-1145``).  The rationale is
stated twice in that source, identically:

    "What we actually interpolate is only the head matrix elements (i.e.
     excluding the 1/q² factor), the wing part that does not diverge (i.e.
     multiplied by |q|), and the complete body element."

LORRAX's coarse→fine densifier (``bse.bse_io.make_w_densifier``) inverse-FFTs
``W_q`` to the coarse R-lattice, zero-pads R and FFTs back — exact band-limited
trigonometric interpolation.  Until this module existed, its operand was the
POST-injection tile ``W_body0(q) + Δ·δ_{q,0}``, with
``Δ = (whead/Ω)·conj(g₀)⊗g₀`` — a Kronecker delta carrying a ~2600 meV
geometric prefactor on the Si anchor deck.  A Kronecker delta is the one
function shape a band-limited interpolant cannot represent: its interpolant is
a Dirichlet kernel, which reproduces the coarse samples exactly and between
them oscillates in sign across the whole fine zone.  Two independent defects
follow.  (i) Ringing: a fraction of that prefactor is deposited at fine
q-points that should carry none of it, including at the zone boundary.
(ii) Missing physics: fine q-points inside the coarse Γ cell should each carry
a LARGE head, because W's head diverges as ``v(q)/ε`` — screening divides the
pole by ε∞, it does not remove it — and no smooth interpolant between Γ's
cell-averaged value and its neighbours produces a 1/q² rise.  So the densified
kernel under-binds excitons near the zone centre, and the error GROWS with the
densification factor instead of shrinking.

WHAT C1 DOES
------------
Split the Γ head off BEFORE the densifier, densify only the body, and
re-attach per fine q::

    W_fine(q) = densify(W_body-only)(q)  +  S_fine(q) · conj(g₀) ⊗ g₀ / Ω

    S_fine(Γ)          = ⟨ v/(1 − v qᵀS_cart q) ⟩ over the FINE mini-BZ cell
    S_fine(q ∈ Γ_c, ≠0) =   v(q)/(1 − v(q) qᵀS_cart q)   evaluated pointwise
    S_fine(q ∉ Γ_c)     =   0

where ``Γ_c`` is the Voronoi cell of Γ with respect to the COARSE q-lattice.
Both expressions come from ONE integrand — the one ``vcoul.Bulk3D.q0_average``
already evaluates — averaged at Γ and evaluated pointwise elsewhere.  Nothing
is derived anew and nothing is fitted.

SHAPE FROM THE INTEGRAND, SCALE FROM THE INJECTED HEAD
------------------------------------------------------
What is actually built is ``S_fine(q) = whead · S_raw(q) / S_raw(Γ_coarse)``:
the q-DEPENDENCE comes from the integrand above, and the overall SCALE is
pinned to ``whead`` — the very scalar the loader injects at q = 0 today.  This
is one multiplication, and it is not a fit; it is what makes the on-grid
identity STRUCTURAL rather than contingent.  Two reasons it has to be there.

*``q0_average`` is a Monte-Carlo estimator.*  It is a scrambled-Sobol average
over the Voronoi cell, deterministic given its options but not a closed form.
Recomputing it at the coarse grid reproduces the restart's ``whead`` bit-for-bit
only if ``nsamples``, ``method``, ``qmc_reps``, ``analytic_sphere`` AND the
scipy that supplies the generator all match what the GW run used.  Pinning the
scale to the injected value makes the identity independent of every one of
those, while the ratio ``whead / S_raw(Γ_coarse)`` — which the wiring logs —
becomes a free PROVENANCE CHECK on exactly that agreement.

*Decks override the head.*  ``vhead`` / ``whead_0freq`` in ``cohsex.in`` are a
cross-code validation knob, and the Si anchor deck uses it
(``whead_0freq = 150.3956``).  On such a deck the injected head is an external
pin and the integrand's own value is not the authority on its magnitude; the
integrand is still the authority on how it varies with q, which is all C1 asks
of it.

Because the anchor is applied as ``whead · (S_raw(q) / S_raw(Γ_coarse))``, the
``fine == coarse`` case divides a float by ITSELF — exactly ``1.0`` — so the
re-attached array is ``[whead at Γ, 0 elsewhere]``, which is today's ``Δ`` to
the last bit.  That is the on-grid bit-identity, obtained by construction.

The restriction to ``Γ_c`` is not a scoping choice, it is what stops a double
count.  At q ≠ 0 LORRAX performs NO head/wing/body separation: the
``argmin |q+G|`` slot sits inside ``V_μν`` and is screened by the full solve,
so every coarse tile at q ≠ 0 already carries its own head, generated by the
inversion.  The only head that was ever removed and re-attached as a scalar is
Γ's, and ``Γ_c`` is exactly the region the removed object was responsible for.
Fine q that coincide with coarse q ≠ 0 points are the centres of their own
coarse cells, hence outside ``Γ_c``, hence get nothing added — which is why the
scheme is consistent at the points where both descriptions are available.

HERMITICITY IS STRUCTURAL, NOT CHECKED
--------------------------------------
``S_fine(q)`` is a REAL scalar (:func:`head_scalar_pointwise` and
:func:`gamma_cell_head_scalar` both return float64) and the update is a real
multiple of the rank-one Hermitian projector ``conj(g₀)⊗g₀`` added to a
Hermitian body.  Hermitian by construction, exactly as the loader's own
injection is.  Reciprocity ``W_q = conj(W_{−q})`` survives because ``S_fine``
depends on q only through ``v(q)`` and ``qᵀSq``, both even.  The rule that
keeps this safe is the one the rejected two-tile shape established: **do not
re-solve; only split and re-attach.**  Nothing here inverts anything, so no
non-congruent product can be formed.

THE ONE APPROXIMATION, NAMED
----------------------------
For fine q-points off the coarse grid the exact projector is
``g₀(q) = ζ̃_{q,μ}(G_q)``, and ζ exists only on the coarse grid.  This stage
FREEZES the projector at ``g₀(Γ)`` for every fine point inside the coarse Γ
cell.  That is an O(q·L) relative error on a term of magnitude O(1/q²) —
controlled inside the cell and irrelevant outside it, and exactly the regime
``THEORY_LT_HEAD_TENSOR.md`` §3.3 identifies as the cell average's validity
domain.  The exact alternatives (``psp/finite_q_head_interp.compute_g_mu_at_q``,
or ``jax.jacfwd`` on the closed-form b26p ζ̃ evaluator) are a later stage.
The freeze enters at exactly one place: :func:`attach_head_channel`, which
takes ONE ``g0`` pair and broadcasts it over every fine q.

WHAT THIS MODULE DOES NOT DO
----------------------------
* It does not modify the q=0 full-expression average.  ``Bulk3D.q0_average``
  is CALLED here, at a different cell size, and never touched — that estimator
  is ratified and is better than BerkeleyGW's 3D product-of-averages.
* It adds no wing term.  The Γ-cell wing second moment ``N_ab = ⟨S q_a q_b⟩``
  is staged separately, measurement-first, because it moves the 0.41 meV
  cross-code parity.
* It is bulk-3D only.  The slab twin needs ``slab_2d.q0_average`` and a
  different trace identity; :func:`build_fine_head_scalars` refuses any other
  ``sys_dim`` rather than silently using the 3D pole.
"""
