def compute_z_factor_from_omega_grid(
	*,
	sigma_c_omega_diag_ev: np.ndarray,  # (n_omega, nk, nb)
	omega_rel_ev: np.ndarray,           # (n_omega,)  — ω axis relative to E_F
	e_dft_rel_ev: np.ndarray,           # (nk, nb)    — the CENTRE, E - E_F
	dE_ev: float = 0.5,
) -> tuple[np.ndarray, np.ndarray]:
	"""Interpolate Σ_c at a centre energy and central-difference
	Z = 1 / (1 − dRe[Σ_c]/dω) there.

	Returns ``(sigma_c_at_centre_diag_ev, z_factor)``, both shape
	``(nk, nb)``.  The Σ_c value is complex; ``z_factor`` is real.

	``e_dft_rel_ev`` NAMES THE CENTRE, and the name is the one-shot case,
	not a claim about every caller.  eqp0 always wants E_DFT − E_F here;
	eqp1 wants the energies the Σ spectrum was BUILT at (see
	:func:`assemble_eqp`), which is the same array in a one-shot run and
	the converged QP energies under self-consistency.  Whatever is passed
	must be ω-relative on the SAME reference the ω grid was built with.

	``dE_ev`` plays the role of BGW's ``finite_difference_spacing``; 0.5 eV
	matches the BGW default.  For the ω-grid spacing of 0.25 eV used by
	gw_jax this falls cleanly on grid points.
	"""
	nk, nb = e_dft_rel_ev.shape
	if sigma_c_omega_diag_ev.shape != (omega_rel_ev.size, nk, nb):
		raise ValueError(
			f"sigma_c_omega shape {sigma_c_omega_diag_ev.shape} mismatched against "
			f"({omega_rel_ev.size}, {nk}, {nb})"
		)

	# ``clamp``, named rather than inherited.  The +/- dE_ev probes are
	# DESIGNED to leave the grid at its two outermost samples -- a central
	# difference at the edge has nowhere else to stand -- so a refusal here
	# would fire on every healthy deck.  What the clamp costs is worth
	# stating: where BOTH probes clamp to the same endpoint the numerator
	# is exactly zero, dRe[sigma_c]/domega comes back 0 and Z comes back
	# exactly 1, i.e. eqp1 degenerates to eqp0 for that state.  That is a
	# recognisable signature rather than a plausible wrong number, which is
	# why it is tolerable here and is not at the OUTPUT path
	# (dynamic_sigma.eval_sigma_c_at_dft_energies, which reports its count).
	from .qsgw_utils import interp_along_omega
	sigma_c_at_dft = interp_along_omega(
		sigma_c_omega_diag_ev, omega_rel_ev, e_dft_rel_ev,
		out_of_range="clamp")
	sigma_c_plus = interp_along_omega(
		sigma_c_omega_diag_ev, omega_rel_ev, e_dft_rel_ev + dE_ev,
		out_of_range="clamp")
	sigma_c_minus = interp_along_omega(
		sigma_c_omega_diag_ev, omega_rel_ev, e_dft_rel_ev - dE_ev,
		out_of_range="clamp")

	# Central-difference dRe[Σ_c]/dω at the centre
	dsigma_dE = (np.real(sigma_c_plus) - np.real(sigma_c_minus)) / (2.0 * dE_ev)
	z_factor = 1.0 / (1.0 - dsigma_dE)
	return sigma_c_at_dft, z_factor


def _implied_vxc_window_ev() -> tuple[float, float]:
	"""The physical window for ``V_xc = E_DFT − (kin_ion + V_H)``, in eV.

	Single-sources the bounds from ``gw.gw_output`` when that module
	exposes them, so the writer-side gate and the driver-side
	``_warn_on_unphysical_h0`` can never drift apart.  The literals below
	are the same numbers, kept as a fallback so this module stays
	importable on its own (the post-hoc ``python -m gw.eqp_bgw`` CLI does
	not otherwise need the driver).
	"""
	try:
		from . import gw_output as _gwo
		return (float(getattr(_gwo, "_VXC_IMPLIED_MIN_EV", -50.0)),
		        float(getattr(_gwo, "_VXC_IMPLIED_MAX_EV", 2.0)))
	except ImportError:
		return (-50.0, 2.0)


def _warn_on_unphysical_implied_vxc(
	*, e_dft_ev, kin_ion_diag_ev, hartree_diag_ev,
) -> None:
	"""Gate the mean-field side of eqp{0,1} on the DFT eigenvalue identity.

	``E_DFT = ⟨T+V_ion+V_NL⟩ + ⟨V_H⟩ + ⟨V_xc⟩`` is exact, so a correct run
	must reproduce a physical ``V_xc = E_DFT − (kin_ion + V_H)``
	band-by-band.  That is the invariant this checks.

	Why not check the QP shift itself.  The first version of this gate
	bracketed ``Δ = eqp0 − E_DFT`` at ±50 eV, reasoning that GW moves
	states by a few eV.  That is **wrong for deep states**: Δ = Σ_xc −
	V_xc, and semicore bands carry bare-exchange Σ_x of order −100 eV
	against an equally large V_xc, so a perfectly healthy run legitimately
	shows |Δ| ≫ 50 eV.  It fired on 72 of 120 states of the cohsex_debug
	fixture — a run that simultaneously reproduced its reference eqp to
	1e-6 eV.  The implied-V_xc form has no such sensitivity: the large,
	legitimate Σ_xc cancels out of it entirely, because Σ never enters.

	This is deliberately the same invariant, and the same window, as
	``gw_output._warn_on_unphysical_h0``.

	**Status:** since AD, :func:`assemble_eqp` runs the source-aware
	``_warn_on_unphysical_h0`` for BOTH entry points, so this function is
	no longer on the live path.  It is retained as (a) the fallback the
	assembly uses when ``gw.gw_output`` is not importable (no jax on the
	host — the post-hoc CLI's own environment) and (b) the ``common.sanity``
	spelling of the same bracket, which the pure-python gate suite calls
	directly.  Warn-only; prints nothing on a healthy run.
	"""
	from common import sanity

	if not sanity.sanity_enabled():
		return
	implied_vxc = (np.asarray(e_dft_ev, dtype=np.float64)
	               - (np.asarray(kin_ion_diag_ev, dtype=np.float64)
	                  + np.real(np.asarray(hartree_diag_ev))))
	lo, hi = _implied_vxc_window_ev()
	sanity.check_in_range(
		"implied Vxc = E_DFT − (kin_ion + V_H)", implied_vxc, lo, hi,
		unit="eV")


def compute_eqp_diag(
	*,
	kin_ion_diag_ev: np.ndarray,        # (nk, nb)
	hartree_diag_ev: np.ndarray,        # (nk, nb)
	sigma_x_diag_ev: np.ndarray,        # (nk, nb)
	sigma_c_at_dft_diag_ev: np.ndarray, # (nk, nb)  — on-shell Σ_c
	e_dft_ev: np.ndarray,               # (nk, nb)
	z_factor: np.ndarray | None = None, # (nk, nb)  — None ⇒ Z=1 (static modes)
	# The eqp1 linearization point, when it is NOT E_DFT (see below).
	# Both or neither; None ⇒ the historical at-DFT linearization.
	sigma_c_at_eval_diag_ev: np.ndarray | None = None,  # (nk, nb)
	e_eval_ev: np.ndarray | None = None,                # (nk, nb)
) -> tuple[np.ndarray, np.ndarray]:
	"""Return zeroth-order and Z-linearized BGW QP energies.

	Computes::

	    Δ(k,n,E) = (kin_ion + V_H + Σ_x + Σ_c(E) − E).real
	    eqp0     = E_DFT + Δ(E_DFT)                  (zeroth-order Newton)
	    eqp1     = E_ref  + Z · Δ(E_ref)             (linearized; Z=1 if None)

	**Where E_ref is, and why it is not always E_DFT.** eqp1 is one Newton
	step on the QP equation ``E = h₀ + ReΣ(E)``, linearized about a
	reference energy; Z = 1/(1 − dΣ/dω) is the derivative AT that same
	reference.  BGW's G0W0 takes E_ref = E_DFT because that is the only
	spectrum a one-shot run has, and this function does the same whenever
	``e_eval_ev is None`` — bit-for-bit the historical expression.  Under
	self-consistency the spectrum Σ was built from is the converged QP
	one, so E_DFT is the wrong place to linearize: the central difference
	then samples Σ(ω) eV away from the pole it is meant to characterise
	(2.4 eV at Γ on the sodium 8×8×8 deck), and the residual Δ it
	multiplies is not small.  Passing the evaluation energies makes the
	step consistent — at convergence Δ(E_qp) ≈ 0 and eqp1 reproduces the
	converged iterate, which is the statement eqp1 is supposed to make.

	eqp0 is UNTOUCHED by this: it stays the at-E_DFT zeroth-order value
	that pairs with the ``E_DFT`` column of the file, in every mode.

	For static modes (COHSEX) the on-shell Σ_c is just the static value and
	there is no ω-grid to differentiate, so callers pass ``z_factor=None``
	and ``eqp1 == eqp0`` trivially — matching BGW's behavior in static runs.

	For dynamic modes (GN-PPM, HL-PPM, MPA) the caller obtains
	``sigma_c_at_dft_diag_ev``, ``sigma_c_at_eval_diag_ev`` and
	``z_factor`` from :func:`compute_z_factor_from_omega_grid`.
	"""
	if (sigma_c_at_eval_diag_ev is None) != (e_eval_ev is None):
		raise ValueError(
			"compute_eqp_diag: sigma_c_at_eval_diag_ev and e_eval_ev are "
			"the two halves of ONE linearization point — pass both or "
			"neither; got "
			f"sigma_c_at_eval={'set' if sigma_c_at_eval_diag_ev is not None else 'None'}, "
			f"e_eval={'set' if e_eval_ev is not None else 'None'}")
	sigma_xc_at_dft = sigma_x_diag_ev + sigma_c_at_dft_diag_ev
	delta_at_dft = (
		kin_ion_diag_ev + hartree_diag_ev + sigma_xc_at_dft - e_dft_ev
	).real

	# NOTE: the mean-field (implied-V_xc) gate deliberately does NOT live
	# here.  ``compute_eqp_diag`` is the pure math kernel, shared by every
	# path including callers that legitimately want no output at all
	# (``gw_output.write_freq_debug``), and a gate here reported one
	# broken H₀ twice in two wordings.  It lives one level up, in
	# :func:`assemble_eqp`, which BOTH entry points go through — so it
	# still fires exactly once on the live driver and on the post-hoc
	# CLI.  Pinned by
	# ``tests/test_sanity_gates.py::test_compute_eqp_diag_does_not_duplicate_the_mean_field_gate``.
	eqp0 = e_dft_ev + delta_at_dft
	if z_factor is None:
		eqp1 = eqp0  # Z=1 trivially
	elif e_eval_ev is None:
		eqp1 = e_dft_ev + z_factor * delta_at_dft
	else:
		delta_at_eval = (
			kin_ion_diag_ev + hartree_diag_ev
			+ sigma_x_diag_ev + sigma_c_at_eval_diag_ev - e_eval_ev
		).real
		eqp1 = e_eval_ev + z_factor * delta_at_eval
	return eqp0, eqp1


# ---------------------------------------------------------------------------
# THE V_H seam — which Hartree term enters H₀, decided in exactly one place
# ---------------------------------------------------------------------------

def resolve_hartree_diag_ev(
	*,
	hartree_diag_ev: np.ndarray,
	hartree_source: str | None = None,
	kin_ion_has_hartree: bool = False,
	exact_hartree_diag_ev: np.ndarray | None = None,
	hartree_already_resolved: bool = False,
	print_fn=print,
) -> tuple[np.ndarray, str]:
	"""Decide the ⟨mk|V_H|mk⟩ term of H₀.  **The only copy of this rule.**

	H₀ = kin_ion + V_H is a ~500 eV catastrophic cancellation, so counting
	the Hartree term twice — or zero times — is the single most damaging
	mistake either eqp entry point can make (production job 7874840:
	QP gap −453 eV at rc=0).  The three-way rule, from
	``file_io.kin_ion``'s source ladder:

	``folded``   (legacy ``has_hartree=True`` with no ``v_hartree``
	             dataset) — V_H is already inside the ``kin_ion`` values.
	             **Suppress**: the Hartree term is zero here.
	``stored``   — ``kin_ion`` is pristine and the file carries the exact
	             FFT-grid V_H in its own array.  **Substitute** it for
	             whatever Σ-side (ISDF quadrature) column the caller
	             brought, when the caller supplies it.
	other        (``isdf`` / ``gspace`` / ``none`` / unknown) —
	             ``hartree_diag_ev`` *is* the run's V_H.  **Use as given.**

	``hartree_already_resolved=True`` is the live-driver contract:
	``gw.sigma_dispatch`` has already applied this scalar source policy at the
	operator seam, and the array may additionally contain a non-scalar direct
	field (the transverse photon Hartree term).  In that case this function
	must preserve the array as given rather than applying the scalar policy a
	second time.  The post-hoc path leaves the flag false and supplies raw
	file columns.

	``exact_hartree_diag_ev`` is the substitution operand and is optional
	on purpose.  The live driver passes an already-resolved ``sig_h`` and no
	substitution operand.  On the post-hoc CLI path nothing upstream applied
	the policy, so ``make_eqp_bgw`` reads ``kin_ion.h5``'s ``v_hartree`` and
	passes it here.

	Reading the file attribute is the only supported discriminator —
	never infer the state from magnitudes (``file_io.kin_ion`` docstring).

	Returns ``(hartree_diag_ev_used, rule)`` where ``rule`` is one of
	``'suppressed'`` / ``'substituted'`` / ``'as-given'``.
	"""
	h = np.real(np.asarray(hartree_diag_ev, dtype=np.float64))
	if bool(hartree_already_resolved):
		if exact_hartree_diag_ev is not None:
			raise ValueError(
				"an already-resolved Hartree input cannot also request an exact "
				"post-hoc substitution")
		print_fn(
			"  V_H seam: live SigmaResult already applied the scalar Hartree "
			"source policy — preserving its resolved direct contribution as given "
			f"(mean magnitude = {float(np.mean(np.abs(h))):.3f} eV).")
		return h, "as-given"
	if bool(kin_ion_has_hartree) or hartree_source == "folded":
		print_fn(
			"  V_H seam: kin_ion carries the exact FFT-grid V_H in its own "
			"values (legacy folded file) — suppressing the Sigma-side "
			f"Hartree column (mean |V_H| = {float(np.mean(np.abs(h))):.3f} eV) "
			"to avoid double counting.")
		return np.zeros_like(h), "suppressed"
	if hartree_source == "stored" and exact_hartree_diag_ev is not None:
		vh = np.real(np.asarray(exact_hartree_diag_ev, dtype=np.float64))
		if vh.shape != h.shape:
			raise ValueError(
				f"exact V_H diagonal shape {vh.shape} does not match the "
				f"Sigma-side Hartree column {h.shape}")
		print_fn(
			"  V_H seam: kin_ion is pristine and carries a stored exact V_H "
			"array — substituting it for the Sigma-side ISDF column "
			f"(mean |V_H| {float(np.mean(np.abs(h))):.3f} → "
			f"{float(np.mean(np.abs(vh))):.3f} eV).")
		return vh, "substituted"
	return h, "as-given"


# ---------------------------------------------------------------------------
# THE assembly — H₀ + Σ → eqp0/eqp1.  Both entry points go through this.
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class EqpAssembly:
	"""Everything the BGW eqp{0,1} formatter needs, and nothing else.

	Produced by :func:`assemble_eqp` — the *only* place the V_H seam, the
	mean-field gate, the Z-factor and the Newton update are applied — and
	consumed by :meth:`write`, which is the *only* BGW formatter.  The
	live driver (``gw.gw_output.write_results``) and the post-hoc CLI
	(:func:`make_eqp_bgw`) differ solely in how they obtain the input
	arrays; from this object onward the two paths are the same code.
	"""

	kpoints_irr_frac: np.ndarray
	band_offset: int
	e_dft_ev: np.ndarray
	eqp0_ev: np.ndarray
	eqp1_ev: np.ndarray
	kin_ion_diag_ev: np.ndarray
	hartree_diag_ev: np.ndarray          # post-seam: the V_H actually used
	sigma_x_diag_ev: np.ndarray
	sigma_c_at_dft_diag_ev: np.ndarray
	#: The exact output-conditioned diagonal curve used to derive both
	#: ``sigma_c_at_dft_diag_ev`` and ``z_factor``.  The persisted full
	#: operator cube remains raw; this smaller curve is an assembly operand.
	sigma_c_omega_diag_ev: np.ndarray | None
	z_factor: np.ndarray | None
	hartree_rule: str                    # 'suppressed' | 'substituted' | 'as-given'
	implied_vxc_ev: np.ndarray | None
	nspin: int = 1
	hartree_source: str | None = None
	kin_ion_has_hartree: bool = False
	#: Where eqp1 was linearized, when that was not E_DFT (self-consistent
	#: runs).  None on every one-shot path, where it IS E_DFT.
	e_eval_ev: np.ndarray | None = None

	def write(self, *, eqp0_path: str, eqp1_path: str) -> tuple[str, str]:
		"""Emit the exact-BGW-format eqp0.dat / eqp1.dat pair."""
		return write_eqp_bgw_pair(
			eqp0_path=eqp0_path, eqp1_path=eqp1_path,
			kpoints_irr_frac=self.kpoints_irr_frac,
			e_dft_ev=self.e_dft_ev,
			eqp0_ev=self.eqp0_ev, eqp1_ev=self.eqp1_ev,
			band_offset=self.band_offset, nspin=self.nspin,
		)


def assemble_eqp(
	*,
	kpoints_irr_frac: np.ndarray,
	band_offset: int,
	e_dft_ev: np.ndarray,                                  # (nk, nb)
	kin_ion_diag_ev: np.ndarray,                           # (nk, nb)
	hartree_diag_ev: np.ndarray,                           # (nk, nb) pre-seam
	sigma_x_diag_ev: np.ndarray,                           # (nk, nb)
	sigma_c_at_dft_diag_ev: np.ndarray | None = None,      # (nk, nb)
	# Optional: full ω-grid for the Z-factor (PPM modes only).
	# If None ⇒ Z=1 ⇒ eqp1 == eqp0 (BGW behaviour in static modes).
	sigma_c_omega_diag_ev: np.ndarray | None = None,       # (n_omega, nk, nb)
	omega_rel_ev: np.ndarray | None = None,                # (n_omega,)
	e_dft_rel_ev: np.ndarray | None = None,                # (nk, nb)
	# The eqp1 linearization point — see step 3 below.  Absolute eV and
	# ω-relative eV of the SAME energies; both or neither.
	e_eval_ev: np.ndarray | None = None,                   # (nk, nb)
	e_eval_rel_ev: np.ndarray | None = None,               # (nk, nb)
	dE_ev: float = 0.5,
	nspin: int = 1,
	# The V_H seam (see resolve_hartree_diag_ev)
	hartree_source: str | None = None,
	kin_ion_has_hartree: bool = False,
	exact_hartree_diag_ev: np.ndarray | None = None,
	hartree_already_resolved: bool = False,
	mean_field_gate: bool = True,
	print_fn=print,
) -> EqpAssembly:
	"""Assemble BGW QP energies from H₀ and Σ.  **One implementation.**

	Order of operations, and each step happens exactly once:

	1. the V_H seam (:func:`resolve_hartree_diag_ev`), resolving a raw
	   post-hoc column or preserving an explicitly resolved live-driver one;
	2. the mean-field gate on the *resolved* H₀
	   (``gw.gw_output._warn_on_unphysical_h0`` — the source-aware
	   implied-V_xc check; warn-only, never raises);
	3. for a dynamic run, derive both Σ_c(E_DFT) and Z from the SAME
	   output-conditioned diagonal C(omega) curve; for a static run, consume
	   the supplied Σ_c diagonal.  When the
	   caller says the Σ spectrum was evaluated somewhere else
	   (``e_eval_ev``), a SECOND interpolation and central-difference
	   Z there, which is where eqp1 is linearized
	   (:func:`compute_z_factor_from_omega_grid`, and
	   :func:`compute_eqp_diag` for why);
	4. the Newton update (:func:`compute_eqp_diag`).

	**The evaluation point, and the one-omega-reference rule.**
	``e_eval_ev`` / ``e_eval_rel_ev`` are the same energies in absolute
	and ω-relative eV, and the caller forms the relative one with the SAME
	reference it formed ``e_dft_rel_ev`` with — the reference the Σ(ω)
	grid was built with, never a second opinion about it.  Passing them
	equal to the DFT arrays is not merely allowed but the one-shot case,
	and the code then takes the single-interpolation path and reproduces
	the historical numbers bit-for-bit.

	The gate lives HERE rather than in ``compute_eqp_diag`` (which must
	stay a silent pure function — pinned by
	``tests/test_sanity_gates.py::test_compute_eqp_diag_does_not_duplicate_the_mean_field_gate``)
	and no longer at the two call sites, so a single broken H₀ reports
	itself exactly once, in one wording, on both entry points.
	"""
	hartree_used, rule = resolve_hartree_diag_ev(
		hartree_diag_ev=hartree_diag_ev,
		hartree_source=hartree_source,
		kin_ion_has_hartree=kin_ion_has_hartree,
		exact_hartree_diag_ev=exact_hartree_diag_ev,
		hartree_already_resolved=hartree_already_resolved,
		print_fn=print_fn,
	)

	implied_vxc = None
	if mean_field_gate:
		implied_vxc = _warn_on_unphysical_h0(
			e_dft_ev=e_dft_ev,
			kin_ion_diag_ev=kin_ion_diag_ev,
			hartree_diag_ev=hartree_used,
			kin_ion_has_hartree=kin_ion_has_hartree,
			hartree_source=hartree_source,
			print_fn=print_fn,
		)
		# No second check here on purpose.  ``_warn_on_unphysical_h0``
		# emits its failure through ``common.sanity.warn``, so the
		# ``*** LORRAX SANITY FAILURE`` grep token and the strict-mode
		# raise both come from that ONE call — for the live driver and
		# for the post-hoc CLI alike.  O's policy kept, its duplicate
		# wording dropped.

	if (e_eval_ev is None) != (e_eval_rel_ev is None):
		raise ValueError(
			"assemble_eqp: e_eval_ev and e_eval_rel_ev are the absolute and "
			"ω-relative halves of ONE linearization point — pass both or "
			"neither")
	sigma_c_at_eval = None
	if sigma_c_omega_diag_ev is None:
		# Static mode: no ω-grid, Z = 1 trivially.
		if sigma_c_at_dft_diag_ev is None:
			raise ValueError(
				"assemble_eqp needs either sigma_c_at_dft_diag_ev (static "
				"modes) or sigma_c_omega_diag_ev + omega_rel_ev + "
				"e_dft_rel_ev (dynamic modes)")
		z_factor = None
		sigma_c_at_dft = sigma_c_at_dft_diag_ev
		# No derivative to centre; eqp1 == eqp0 whatever was passed.
		e_eval_ev = None
	else:
		if omega_rel_ev is None or e_dft_rel_ev is None:
			raise ValueError(
				"sigma_c_omega_diag_ev requires omega_rel_ev and e_dft_rel_ev")
		if sigma_c_at_dft_diag_ev is not None:
			raise ValueError(
				"dynamic assemble_eqp derives both C(E_DFT) and Z from its one "
				"sigma_c_omega_diag_ev curve; a second C(E_DFT) operand would "
				"duplicate the correlation producer.")
		sigma_c_at_dft, z_factor = compute_z_factor_from_omega_grid(
			sigma_c_omega_diag_ev=sigma_c_omega_diag_ev,
			omega_rel_ev=omega_rel_ev,
			e_dft_rel_ev=e_dft_rel_ev,
			dE_ev=dE_ev,
		)
		# THE SECOND CENTRE, and only when it is a different one.  The
		# equality test is what keeps every one-shot run — where the Σ
		# spectrum IS evaluated at E_DFT, so the caller passes the same
		# numbers — on the single-centre code above.  It is an
		# ``array_equal``, not a tolerance:
		# these arrays are either literally the same energies or a
		# different spectrum.
		if e_eval_rel_ev is not None and not np.array_equal(
			np.asarray(e_eval_rel_ev, dtype=np.float64),
			np.asarray(e_dft_rel_ev, dtype=np.float64),
		):
			sigma_c_at_eval, z_factor = compute_z_factor_from_omega_grid(
				sigma_c_omega_diag_ev=sigma_c_omega_diag_ev,
				omega_rel_ev=omega_rel_ev,
				e_dft_rel_ev=e_eval_rel_ev,
				dE_ev=dE_ev,
			)
			print_fn(
				"  eqp1 linearization: Σ was evaluated away from E_DFT this "
				f"call (max |E_eval − E_DFT| = "
				f"{float(np.max(np.abs(np.asarray(e_eval_ev, dtype=np.float64) - np.asarray(e_dft_ev, dtype=np.float64)))):.4f} eV) "
				"— Z and the Σ_c it multiplies are centred there, not at "
				"E_DFT.  eqp0 stays at E_DFT.")
		else:
			e_eval_ev = None

	eqp0_ev, eqp1_ev = compute_eqp_diag(
		kin_ion_diag_ev=kin_ion_diag_ev,
		hartree_diag_ev=hartree_used,
		sigma_x_diag_ev=sigma_x_diag_ev,
		sigma_c_at_dft_diag_ev=sigma_c_at_dft,
		e_dft_ev=e_dft_ev,
		z_factor=z_factor,
		sigma_c_at_eval_diag_ev=sigma_c_at_eval,
		e_eval_ev=e_eval_ev,
	)
	return EqpAssembly(
		kpoints_irr_frac=np.asarray(kpoints_irr_frac, dtype=np.float64),
		band_offset=int(band_offset),
		e_dft_ev=np.asarray(e_dft_ev, dtype=np.float64),
		eqp0_ev=eqp0_ev, eqp1_ev=eqp1_ev,
		kin_ion_diag_ev=kin_ion_diag_ev,
		hartree_diag_ev=hartree_used,
		sigma_x_diag_ev=sigma_x_diag_ev,
		sigma_c_at_dft_diag_ev=sigma_c_at_dft,
		sigma_c_omega_diag_ev=(
			None if sigma_c_omega_diag_ev is None
			else np.asarray(sigma_c_omega_diag_ev, dtype=np.complex128)),
		z_factor=z_factor,
		hartree_rule=rule,
		implied_vxc_ev=implied_vxc,
		nspin=int(nspin),
		hartree_source=hartree_source,
		kin_ion_has_hartree=bool(kin_ion_has_hartree),
		e_eval_ev=(None if e_eval_ev is None
		           else np.asarray(e_eval_ev, dtype=np.float64)),
	)


def _warn_on_unphysical_h0(**kwargs):
	"""The source-aware mean-field gate, single-sourced from the driver.

	Lives in ``gw.gw_output`` (with its window constants) because that is
	where the diagnosis text belongs; imported lazily here so this module
	stays importable on its own for the post-hoc CLI, exactly as
	:func:`_implied_vxc_window_ev` does.  If the driver is not importable
	(no jax on the host) the assembly falls back to the local
	warn-only bracket rather than skipping the check.
	"""
	try:
		from . import gw_output as _gwo
	except ImportError:
		_warn_on_unphysical_implied_vxc(
			e_dft_ev=kwargs["e_dft_ev"],
			kin_ion_diag_ev=kwargs["kin_ion_diag_ev"],
			hartree_diag_ev=kwargs["hartree_diag_ev"],
		)
		return None
	return _gwo._warn_on_unphysical_h0(**kwargs)


def write_eqp_bgw_pair(
	*,
	eqp0_path: str,
	eqp1_path: str,
	kpoints_irr_frac: np.ndarray,
	e_dft_ev: np.ndarray,
	eqp0_ev: np.ndarray,
	eqp1_ev: np.ndarray,
	band_offset: int,
	nspin: int = 1,
) -> tuple[str, str]:
	"""Write the BGW-format eqp0.dat + eqp1.dat pair from precomputed arrays.

	Both files share the same provenance header, k-point list, and
	``E_DFT`` column; only the ``E_QP`` column differs (zeroth-order
	vs. Z-linearized).
	"""
	write_bgw_eqp(eqp0_path, kpoints_irr_frac, e_dft_ev, eqp0_ev,
	              band_offset=band_offset, nspin=nspin)
	write_bgw_eqp(eqp1_path, kpoints_irr_frac, e_dft_ev, eqp1_ev,
	              band_offset=band_offset, nspin=nspin)
	return eqp0_path, eqp1_path


#: Occupations this far from an integer are FRACTIONAL, i.e. a smeared
#: Fermi surface.  Loose on purpose: the question here is "is there a
#: mid-gap to fall back on", and one partially filled state anywhere in
#: the BZ answers it, whatever the smearing width.
_OCC_INTEGER_TOL = 1.0e-6


def _metallic_occupations(ifmax, occupations):
	"""``(metallic, why)`` from a WFN's own occupation record.

	TWO INDEPENDENT SIGNATURES, either of which means "no mid-gap exists":

	* ``ifmax`` — the highest occupied band, per k — is not the same at
	  every k.  That is a band crossing E_F, which is what a Fermi surface
	  IS; ``max(ifmax)`` then names a band that is empty at some k, and
	  ½(VBM+CBM) computed across that split is not a gap centre.
	* any occupation is strictly fractional.  A smeared metal's states at
	  E_F are partially filled by construction.

	Reported separately because they answer different questions when a
	reader comes back to a refusal: the first is geometry, the second is
	smearing.  ``occupations=None`` (a WFN without the dataset) simply
	does not contribute its half.
	"""
	reasons = []
	ifmax = np.asarray(ifmax)
	if ifmax.size and int(np.min(ifmax)) != int(np.max(ifmax)):
		reasons.append(
			f"ifmax varies across k ({int(np.min(ifmax))}..{int(np.max(ifmax))}"
			") — a band crosses E_F")
	if occupations is not None:
		occ = np.asarray(occupations, dtype=np.float64)
		frac = np.abs(occ - np.rint(occ)) > _OCC_INTEGER_TOL
		if bool(np.any(frac)):
			reasons.append(
				f"{int(np.count_nonzero(frac))} of {occ.size} occupations "
				f"are fractional (max deviation "
				f"{float(np.max(np.abs(occ - np.rint(occ)))):.3e})")
	return bool(reasons), "; ".join(reasons) or "insulating"


