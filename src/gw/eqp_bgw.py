def write_bgw_eqp(
	path: str,
	kpoints_irr_frac: np.ndarray,
	e_dft_ev: np.ndarray,
	e_qp_ev: np.ndarray,
	*,
	band_offset: int,
	nspin: int = 1,
	comments: tuple[str, ...] = (),
) -> str:
	"""Write a BerkeleyGW ``eqp{0,1}.dat`` file.

	Parameters
	----------
	path
	    Output file path.
	kpoints_irr_frac : (nk, 3)
	    IBZ-wedge k-points in fractional crystal coordinates.
	e_dft_ev, e_qp_ev : (nk, nb)
	    DFT and quasiparticle eigenvalues in eV, indexed over the
	    sigma-window bands.
	band_offset
	    0-based absolute band index of the first sigma-window band; the
	    BGW file uses 1-based labels ``band_offset + 1 .. band_offset + nb``.
	nspin
	    Number of spin channels (LORRAX runs at nspin=1).
	comments
	    Optional diagnostic lines written after the provenance header.  The
	    formatter supplies the leading ``# `` so the file remains readable by
	    BerkeleyGW-compatible parsers.  The ordinary ``eqp0.dat`` / ``eqp1.dat``
	    path passes none and remains byte-identical to the historical format.
	"""
	kpts = np.asarray(kpoints_irr_frac, dtype=np.float64)
	e_dft = np.asarray(e_dft_ev, dtype=np.float64)
	e_qp = np.asarray(e_qp_ev, dtype=np.float64)
	nk, nb = e_dft.shape
	if kpts.shape != (nk, 3):
		raise ValueError(f"kpoints shape {kpts.shape} does not match e_dft {(nk, 3)}")
	if e_qp.shape != (nk, nb):
		raise ValueError(f"e_qp shape {e_qp.shape} does not match e_dft {(nk, nb)}")

	# ── Writer gate (pre-write) ──────────────────────────────────────
	# The NaN-producing distributed back-solve of 2026-07 reached disk
	# with rc=0 and was caught only because somebody afterwards counted
	# the floats in eqp0.dat: ``%15.9f`` renders a NaN as the token
	# ``nan``, so the *count of parseable floats* drops while the line
	# count does not.  That check is made structural here — the writer
	# refuses to pretend a NaN-bearing array is a result, and re-reads
	# what it wrote to confirm the file it produced parses to exactly the
	# expected number of finite floats.
	# REFUSAL, not a warning.  The 2026-08-15 bcc-Fe run wrote 7176 of 7176
	# E_QP entries as NaN through this very call and exited rc=0; the warning
	# it emitted is the only thing that noticed, and a warning does not reach
	# an exit code (JID 57051742, CLAIMS 204).  A file whose QP column is not
	# a number is not a result, and the reader downstream cannot tell the
	# difference from the line count.  ``LORRAX_ALLOW_NONFINITE_RESULT=1``
	# writes it anyway, for the forensic case, and says so.
	from common import sanity
	sanity.refuse_nonfinite(
		f"{os.path.basename(path)} E_DFT column", e_dft,
		detail="the mean-field spectrum this file reports beside the QP one.")
	sanity.refuse_nonfinite(
		f"{os.path.basename(path)} E_QP column", e_qp,
		detail="%15.9f renders a NaN as the token 'nan', so the file would "
		       "look complete while its numbers were not.")

	abs_path = os.path.abspath(path)
	if os.path.dirname(abs_path):
		os.makedirs(os.path.dirname(abs_path), exist_ok=True)

	with open(abs_path, "w") as fh:
		fh.write(provenance_header())
		for comment in comments:
			line = str(comment)
			if "\n" in line or "\r" in line:
				raise ValueError(
					"write_bgw_eqp comments must each be one line; got "
					f"{line!r}")
			fh.write(f"# {line}\n")
		for ik in range(nk):
			kx, ky, kz = (float(kpts[ik, j]) for j in range(3))
			# Fortran (3f13.9, i8)
			fh.write(f"{kx:13.9f}{ky:13.9f}{kz:13.9f}{nspin * nb:8d}\n")
			for ispin in range(1, nspin + 1):
				for ib in range(nb):
					iband = band_offset + ib + 1  # 1-based BGW absolute band
					# Fortran (2i8, 2f15.9) — BGW format consumes only 4 args
					# even though the spec advertises 3f15.9; sigma_main.f90 passes
					# (ispin, iband, E_DFT, E_QP).
					fh.write(
						f"{ispin:8d}{iband:8d}"
						f"{float(e_dft[ik, ib]):15.9f}{float(e_qp[ik, ib]):15.9f}\n"
					)
	verify_eqp_file(abs_path, nk=nk, nb=nb, nspin=nspin)
	return abs_path


def read_bgw_eqp(eqp_file: str):
	"""Read a BerkeleyGW ``eqp{0,1}.dat`` — the inverse of :func:`write_bgw_eqp`.

	Returns ``(kpts_irr (nk, 3), e_dft (nk, nb), e_qp (nk, nb),
	band_offset)``; the energies are eV and the k-points are the CRYSTAL
	COORDINATES the block headers carry, on the irreducible wedge the
	writer emitted.

	``band_offset`` is the 0-BASED ABSOLUTE index of column 0, recovered
	from the file's own 1-based ``iband`` labels — the inverse of
	:func:`write_bgw_eqp`'s ``band_offset``.  It is returned rather than
	dropped because a consumer slicing an absolute band window
	(``bandstructure.htransform``) cannot place these columns without it,
	and the previous reader discarded it, which is why that consumer grew
	a second eqp parser instead of using this one.

	**Lives beside the writer on purpose.**  It used to sit in
	``bse.bse_window``, which made it reachable only from BSE — so
	``bandstructure.htransform`` grew a second, incompatible eqp parser of
	its own rather than take a ``bandstructure → bse`` edge that exists
	nowhere else in the tree.  One format, one reader, one writer, in one
	module: a change to the layout cannot now update only half of them.

	Ragged band counts are tolerated (short blocks are NaN-padded to the
	widest), because a caller slicing a band window must be able to see
	which states are absent rather than read a zero.
	"""
	kpts: list[list[float]] = []
	e_dft_blocks: list[list[float]] = []
	e_qp_blocks: list[list[float]] = []
	first_band: int | None = None

	with open(eqp_file) as f:
		while True:
			header = f.readline()
			if not header:
				break
			stripped = header.strip()
			if not stripped:
				break
			if stripped.startswith("#"):
				continue
			parts = header.split()
			if len(parts) < 4:
				break
			kpts.append([float(parts[0]), float(parts[1]), float(parts[2])])
			n_bands = int(parts[3])

			e_dft_k, e_qp_k = [], []
			for _ in range(n_bands):
				cols = f.readline().split()
				# (ispin, iband, E_DFT, E_QP); iband is 1-based ABSOLUTE.
				if first_band is None:
					first_band = int(cols[1])
				e_dft_k.append(float(cols[2]))
				e_qp_k.append(float(cols[3]))
			e_dft_blocks.append(e_dft_k)
			e_qp_blocks.append(e_qp_k)

	if not kpts:
		raise ValueError(
			f"no k-point blocks parsed from {os.path.basename(eqp_file)} — "
			f"expected the BerkeleyGW eqp layout this module writes "
			f"(a '(3f13.9,i8)' k header, then that many '(2i8,2f15.9)' rows)")

	max_band = max(len(b) for b in e_dft_blocks)
	n_kpts = len(kpts)
	e_dft = np.full((n_kpts, max_band), np.nan)
	e_qp = np.full((n_kpts, max_band), np.nan)
	for i in range(n_kpts):
		nb = len(e_dft_blocks[i])
		e_dft[i, :nb] = e_dft_blocks[i]
		e_qp[i, :nb] = e_qp_blocks[i]
	return np.array(kpts), e_dft, e_qp, int(first_band) - 1


def verify_eqp_file(
	path: str, *, nk: int, nb: int, nspin: int = 1,
	print_fn=print,
) -> bool:
	"""Re-read a written ``eqp*.dat`` and assert its structural float count.

	The invariant: after the ``#`` provenance line the file holds ``nk``
	k-point headers (3 floats + 1 int) and ``nk·nspin·nb`` body rows
	(2 ints + 2 floats).  So a healthy file parses to exactly

	    n_float = nk·3 + nk·nspin·nb·2

	*finite* floats.  ``float("nan")`` parses fine, so the count alone is
	not enough — non-finite tokens are counted separately and reported.
	This is the check that caught the NaN-producing back-solve after the
	fact; running it inside the writer turns "somebody noticed later" into
	"the run said so at the time".

	Returns True when the file is structurally sound.  Cost is one pass
	over a few-thousand-line text file, i.e. nothing.
	"""
	from common import sanity

	if not sanity.sanity_enabled():
		return True
	expect_rows = int(nk) * int(nspin) * int(nb)
	expect_floats = int(nk) * 3 + expect_rows * 2
	n_float = 0
	n_nonfinite = 0
	n_header = 0
	n_body = 0
	with open(path, "r") as fh:
		for line in fh:
			if line.startswith("#") or not line.strip():
				continue
			tok = line.split()
			# Header rows are (3f13.9, i8) — the first token is a float and
			# carries a '.'.  Body rows are (2i8, 2f15.9) — the first two
			# tokens are bare integers.  Discriminating on content rather
			# than column width keeps this correct if either format ever
			# widens a field.
			if len(tok) == 4 and "." in tok[0]:
				n_header += 1
				vals = tok[:3]
			elif len(tok) == 4:
				n_body += 1
				vals = tok[2:]
			else:
				n_nonfinite += len(tok)   # malformed → count as suspect
				continue
			for v in vals:
				try:
					x = float(v)
				except ValueError:
					n_nonfinite += 1
					continue
				if np.isfinite(x):
					n_float += 1
				else:
					n_nonfinite += 1
	base = os.path.basename(path)
	ok = sanity.check_count(
		f"{base} finite-float count", n_float, expect_floats,
		print_fn=print_fn,
		detail=(f"{n_header}/{nk} k-headers, {n_body}/{expect_rows} band rows, "
		        f"{n_nonfinite} non-finite/unparseable tokens.  A NaN or Inf "
		        f"in the QP column renders as a token %15.9f cannot round-trip "
		        f"— the file looks complete but its numbers are not."))
	ok = sanity.check_count(f"{base} band rows", n_body, expect_rows,
	                        print_fn=print_fn) and ok
	return ok


