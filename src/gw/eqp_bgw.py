def _read_eval_energies_ev(
	path: str, *, kirr_to_kfull: np.ndarray, band_start: int, band_stop: int,
) -> np.ndarray:
	"""The IBZ × sigma-window energies (eV) a QP artifact carries.

	Reads either of the two files a run writes its converged spectrum to,
	because both are legitimate answers to "what did Σ get evaluated at"
	and which one is on disk depends on the deck:

	``qp_wfn_rotations.h5`` — ``E_qp_nk_rydberg``, ALREADY on the sigma
	    window (its band axis is ``band_range``), so it is indexed by
	    ``kirr_to_kfull`` and not sliced in bands.  It is read through
	    ``file_io.qp_wfn.read_qp_rotations_full_bz`` because that array may
	    be stored on the file wedge; ``kirr_to_kfull`` is always a full-BZ
	    index, so the indexing below is unchanged either way.  A file with
	    no ``k_storage`` attr comes back verbatim.
	``WFN_qp.h5``           — ``mf_header/kpoints/el``, the WFN file's own
	    k-set (the IBZ) and ALL bands, so it is sliced in bands and not
	    in k.
	"""
	with h5py.File(path, "r") as f:
		has_rot = "E_qp_nk_rydberg" in f
	if has_rot:
		from file_io.qp_wfn import read_qp_rotations_full_bz
		e = np.asarray(read_qp_rotations_full_bz(
			path, datasets=("E_qp_nk_rydberg",))["E_qp_nk_rydberg"],
			dtype=np.float64)
		return e[np.asarray(kirr_to_kfull, dtype=np.int64)] * RYD_TO_EV
	with h5py.File(path, "r") as f:
		if "mf_header/kpoints/el" in f:
			e = np.asarray(f["mf_header/kpoints/el"], dtype=np.float64)
			return e[0][:, int(band_start):int(band_stop)] * RYD_TO_EV
	raise ValueError(
		f"{os.path.basename(path)} carries neither 'E_qp_nk_rydberg' "
		f"(qp_wfn_rotations.h5) nor 'mf_header/kpoints/el' (WFN_qp.h5); it "
		f"cannot say what energies Sigma was evaluated at.")


def make_eqp_bgw(
	run_dir: str,
	*,
	wfn_path: Optional[str] = None,
	kin_ion_path: Optional[str] = None,
	sigma_mnk_path: Optional[str] = None,
	qp_rotations_path: Optional[str] = None,
	eval_energies_path: Optional[str] = None,
	eqp0_out: str = "eqp0.dat",
	eqp1_out: str = "eqp1.dat",
	finite_difference_spacing_ev: float = 0.5,
) -> tuple[str, str]:
	"""Emit BGW-format ``eqp0.dat`` and ``eqp1.dat`` from a LORRAX gw_jax run.

	All file paths default to standard names inside ``run_dir``.  Returns
	``(eqp0_path, eqp1_path)``.

	``eval_energies_path`` — WHERE eqp1 IS LINEARIZED — is the explicit
	OVERRIDE, and it is no longer the only way to get this right.  The two
	candidates on disk are not interchangeable: for a SELF-CONSISTENT run
	``WFN_qp.h5`` / ``qp_wfn_rotations.h5`` hold exactly the converged
	energies Σ was built from and are the right answer, while for a
	ONE-SHOT run those same files hold ``eigh(H₀+Σ)`` — an OUTPUT of the Σ
	that was built at E_DFT, and centring the linearization there would be
	a different, wrong calculation.

	Since 2026-08-22 ``sigma_mnk.h5`` STAMPS which of the two its cube is
	(``file_io.sigma_output.read_eval_energies``), so absent this argument
	this function reads the stamp instead of guessing.  Three outcomes, and
	they are deliberately distinguishable: a stamp saying ``at_e_dft``
	keeps the historical E_DFT centring and says so; a stamp saying
	``self_consistent_qp`` supplies the converged spectrum; and an
	UNSTAMPED file — a cube written before the stamp existed — falls back
	to E_DFT with a printed line saying that is what happened and why it
	may be wrong.  "No stamp" and "stamped at E_DFT" used to look
	identical, and that is the whole defect.  See :func:`compute_eqp_diag`.
	"""
	wfn_path = wfn_path or os.path.join(run_dir, "WFN.h5")
	kin_ion_path = kin_ion_path or os.path.join(run_dir, "kin_ion.h5")
	sigma_mnk_path = sigma_mnk_path or os.path.join(run_dir, "sigma_mnk.h5")
	qp_rotations_path = qp_rotations_path or os.path.join(run_dir, "qp_wfn_rotations.h5")
	eqp0_path = (
		eqp0_out if os.path.isabs(eqp0_out) else os.path.join(run_dir, eqp0_out)
	)
	eqp1_path = (
		eqp1_out if os.path.isabs(eqp1_out) else os.path.join(run_dir, eqp1_out)
	)

	# IBZ k-points + per-state DFT energies (Ry → eV)
	with h5py.File(wfn_path, "r") as wfn:
		kpoints_irr = np.asarray(wfn["mf_header/kpoints/rk"])
		nspin = int(np.asarray(wfn["mf_header/kpoints/nspin"]))
		# energies: (nspin, nk, nbands_total) in Ry
		energies_ry = np.asarray(wfn["mf_header/kpoints/el"])
		ifmax = np.asarray(wfn["mf_header/kpoints/ifmax"])  # (nspin, nk) 1-based
		occupations = (np.asarray(wfn["mf_header/kpoints/occ"])
		               if "mf_header/kpoints/occ" in wfn else None)
	if nspin != 1:
		raise NotImplementedError("LORRAX runs at nspin=1; got nspin={}".format(nspin))

	nk_irr = kpoints_irr.shape[0]

	# IBZ → full-BZ index map; band_range
	with h5py.File(qp_rotations_path, "r") as qp:
		band_range = np.asarray(qp["band_range"], dtype=np.int64)
		kirr_to_kfull = np.asarray(qp["kirr_to_kfull"], dtype=np.int64)
	band_start, band_stop = int(band_range[0]), int(band_range[1])
	nb_window = band_stop - band_start
	if kirr_to_kfull.size != nk_irr:
		raise ValueError(
			f"kirr_to_kfull size {kirr_to_kfull.size} != IBZ kpts {nk_irr}"
		)

	# DFT energies on the IBZ wedge for the sigma window (eV)
	# energies_ry shape (nspin=1, nk_irr, nb_total); take spin 0.
	e_dft_ev = energies_ry[0, :, band_start:band_stop] * RYD_TO_EV
	if e_dft_ev.shape != (nk_irr, nb_window):
		raise ValueError(
			f"WFN energies shape {energies_ry.shape} inconsistent with "
			f"band_range {(band_start, band_stop)} on {nk_irr} IBZ kpts"
		)

	# Decide the format BEFORE touching any raw operator payload.  A complete
	# schema-v3 artifact is served entirely by its small completed-assembly
	# receipt plus omega/evaluation metadata from the same owner-routed open.
	# Only a truly legacy file enters the format owner's diagonal hyperslab
	# reader, which never materializes a full (nω,nk,nb,nb) cube on rank 0.
	from file_io.sigma_output import (
		read_eqp_assembly_receipt,
		read_sigma_eqp_diagonal_window,
	)
	_receipt = read_eqp_assembly_receipt(sigma_mnk_path)
	_legacy_sigma = None
	if _receipt is None:
		_legacy_sigma = read_sigma_eqp_diagonal_window(
			sigma_mnk_path,
			full_bz_rows=kirr_to_kfull,
			band_start=band_start,
			band_stop=band_stop,
		)
		omega_rel_ev = _legacy_sigma["omega_rel_ev"]
		stamped_ev = _legacy_sigma["omega_reference_ev"]
		stamped_provenance = _legacy_sigma["omega_reference_provenance"]
		_eval_rel_window = _legacy_sigma["eval_energies_rel_ev"]
		_eval_prov = _legacy_sigma["eval_energies_provenance"]
		_eval_cov = _legacy_sigma["eval_coverage"]
		sigma_x_diag = _legacy_sigma["sigma_x_diag_ev"]
		hartree_diag = _legacy_sigma["hartree_diag_ev"]
		sigma_c_omega_diag = _legacy_sigma["sigma_c_omega_diag_ev"]
	else:
		omega_rel_ev = _receipt["omega_rel_ev"]
		stamped_ev = _receipt["omega_reference_ev"]
		stamped_provenance = _receipt["omega_reference_provenance"]
		_eval_rel_window = _receipt["eval_energies_rel_ev"]
		_eval_prov = _receipt["eval_energies_provenance"]
		_eval_cov = _receipt["eval_coverage"]

	# ── THE ω REFERENCE: the file's stamp first, midgap only as a legacy
	#    fallback on a file that is demonstrably insulating (audit A2) ──
	#
	# ``sigma_mnk.h5``'s ω axis is RELATIVE, and which zero it is relative
	# to is a property of the RUN that wrote it, not of the WFN this
	# function can see.  The in-run consumers take the finalizer's
	# ``efermi_dft_ev``; this CLI used to recompute ½(VBM+CBM) instead,
	# which on the metal path samples Σ_c(ω) at energies shifted by
	# (mu − midgap) — a measured 2.79 eV on the sodium deck, showing up as
	# a spurious ~+2.4 eV near-E_F QP correction.  So: prefer the stamp;
	# where there is none, fall back to midgap ONLY if the occupations say
	# insulating, and REFUSE otherwise rather than guess wrong by default.
	metallic, why = _metallic_occupations(ifmax, occupations)

	if stamped_ev is not None:
		efermi_ev = float(stamped_ev)
	elif metallic:
		raise ValueError(
			f"make_eqp_bgw: {os.path.basename(sigma_mnk_path)} carries no "
			f"omega_reference_ev stamp, and {os.path.basename(wfn_path)} "
			f"has METALLIC occupations ({why}).\n"
			f"  got  : an unstamped Sigma_c(omega) cube whose axis zero is "
			f"unknown, and a run whose zero is the fixed-N chemical "
			f"potential mu, not mid-gap.\n"
			f"  want : the reference the run interpolated with.  Assuming "
			f"mid-gap here samples Sigma_c at energies shifted by "
			f"(mu - midgap) — 2.79 eV on the sodium deck — and produces "
			f"eqp files that look plausible and are wrong.  There is no "
			f"mid-gap on a metal: the band that would define it crosses "
			f"E_F.\n"
			f"  fix  : regenerate sigma_mnk.h5 with a driver that stamps "
			f"omega_reference_ev (every write since audit A2 does), or "
			f"take eqp0/eqp1 from the run's own output rather than "
			f"reassembling them from disk.  Any comparison already made "
			f"from an unstamped metallic cube through this path is "
			f"invalid.")
	else:
		# Mid-gap Fermi level from the IBZ DFT energies — the pre-stamp
		# insulating convention, kept so every file written before the
		# stamp existed still assembles bit-identically.
		n_occ = int(np.max(ifmax[0]))                   # 1-based highest occ
		occ_idx_local = n_occ - 1 - band_start          # within the window
		if occ_idx_local < 0 or occ_idx_local + 1 >= nb_window:
			raise ValueError(
				"sigma window does not bracket VBM/CBM: band_range="
				f"[{band_start},{band_stop}), VBM index={n_occ - 1}"
			)
		vbm_ev = float(np.max(e_dft_ev[:, : occ_idx_local + 1]))
		cbm_ev = float(np.min(e_dft_ev[:, occ_idx_local + 1 :]))
		efermi_ev = 0.5 * (vbm_ev + cbm_ev)
		stamped_provenance = "midgap (unstamped file, insulating occupations)"
	print(f"  omega reference = {efermi_ev:.6f} eV ({stamped_provenance})")
	e_dft_rel_ev = e_dft_ev - efermi_ev

	# The eqp1 linearization point, on the SAME reference — one subtraction
	# with one ω zero, exactly as the line above.
	e_eval_ev = e_eval_rel_ev = None
	if eval_energies_path is not None:
		e_eval_ev = _read_eval_energies_ev(
			eval_energies_path, kirr_to_kfull=kirr_to_kfull,
			band_start=band_start, band_stop=band_stop)
		if e_eval_ev.shape != e_dft_ev.shape:
			raise ValueError(
				f"eval energies from {os.path.basename(eval_energies_path)} "
				f"have shape {e_eval_ev.shape}, but the sigma window on the "
				f"IBZ is {e_dft_ev.shape}")
		e_eval_rel_ev = e_eval_ev - efermi_ev
		print(f"  eqp1 linearized at {os.path.basename(eval_energies_path)} "
		      f"(max |E_eval − E_DFT| = "
		      f"{float(np.max(np.abs(e_eval_ev - e_dft_ev))):.4f} eV)")

	# kin_ion (Ry → eV), pulled on the IBZ wedge directly.
	#
	# THROUGH ``read_full_bz_dataset``, not a raw h5py read: the file
	# stores the IBZ slab and unfolds on read, so a bare
	# ``kih["kin_ion"]`` here would hand ``kirr_to_kfull`` — full-BZ
	# indices — an ``(nrk, nb, nb)`` array.  Imported lazily (as
	# ``gw.sigma_dispatch`` does) so this module stays importable without
	# pulling in the jax-dependent file_io stack; the V_H seam below takes
	# the same import for the same reason and they are one statement.
	from file_io.kin_ion import (HARTREE_DATASET, kin_ion_hartree_source,
	                             read_full_bz_dataset)
	kin_full = read_full_bz_dataset(kin_ion_path, "kin_ion")
	if kin_full.ndim != 3:
		raise ValueError(f"kin_ion dataset must be (nk, nb, nb); got {kin_full.shape}")
	kin_irr = kin_full[kirr_to_kfull, band_start:band_stop, band_start:band_stop]
	kin_ion_diag_ev = np.real(np.diagonal(kin_irr, axis1=1, axis2=2)) * RYD_TO_EV

	# Sigma payload selection already happened above, before this unrelated
	# mean-field read: schema v3 supplied only its small receipt, while the
	# legacy route supplied exact requested diagonals through the format-owned
	# row/window hyperslab reader.
	# ── THE LINEARIZATION POINT, FROM THE FILE'S OWN STAMP ────────────
	# ``eval_energies_path`` (above) is the explicit override and still
	# wins; this is the case where nobody passed one.  Before the stamp
	# existed this function could not tell a one-shot cube from a
	# self-consistent one and defaulted to E_DFT: correct for the first,
	# a DIFFERENT CALCULATION for the second, and silent either way.  Now
	# an unstamped file and a file that says "at_e_dft" are distinguishable
	# — the first is an absence and says so out loud, the second is a fact.
	#
	# The format owner already selected this small stamp onto the exact
	# requested file rows and Sigma band window alongside the payload route,
	# so there is no second row remap here.
	from file_io.sigma_output import SIGMA_EVAL_AT_E_DFT
	if e_eval_rel_ev is None:
		if _eval_rel_window is None:
			print(f"  eqp1 linearization: {os.path.basename(sigma_mnk_path)} "
			      f"carries NO evaluation-energy stamp (a file written before "
			      f"2026-08-22).  Falling back to E_DFT, which is correct for "
			      f"a one-shot cube and WRONG for a self-consistent one — "
			      f"pass --eval-energies, or regenerate the cube with a "
			      f"driver that stamps it.")
		elif str(_eval_prov) == SIGMA_EVAL_AT_E_DFT:
			print(f"  eqp1 linearization: stamped {_eval_prov!r} — E_DFT, "
			      f"which is what the historical default did.")
		else:
			_sub = np.asarray(_eval_rel_window, dtype=np.float64)
			if _sub.shape != e_dft_rel_ev.shape:
				raise ValueError(
					f"{os.path.basename(sigma_mnk_path)}'s evaluation-energy "
					f"stamp has IBZ/window shape {_sub.shape} against E_DFT "
					f"{e_dft_rel_ev.shape}; the stamp and the cube disagree "
					f"about the k set or the band window.")
			e_eval_rel_ev = _sub
			e_eval_ev = _sub + efermi_ev
			print(f"  eqp1 linearization: stamped {_eval_prov!r} "
			      f"(max |E_eval − E_DFT| = "
			      f"{float(np.max(np.abs(e_eval_ev - e_dft_ev))):.4f} eV)")
		if _eval_cov and int(_eval_cov["n_uncovered"]):
			print(f"  omega coverage (stamped): "
			      f"{_eval_cov['n_uncovered']} evaluation energies "
			      f"({100.0 * _eval_cov['fraction_uncovered']:.1f}%) lie "
			      f"outside the sampled grid; policy="
			      f"{_eval_cov['policy']}.  Those states' sigC is an "
			      f"endpoint value, not Sigma at their own energy.")

	# ── The persisted live-assembly receipt, or the legacy raw seam ─────
	# New sigma_mnk.h5 files keep the full H/X/C(omega) operator cubes RAW
	# (complete off-diagonals, pre-output conditioning) and carry a receipt with
	# the exact conditioned H/X/C(E_DFT) diagonals the live writer handed
	# assemble_eqp.
	# Consume that receipt as data; do NOT re-run degenerate-set averaging
	# here, which would be a second physics owner and is impossible to do
	# correctly for every SC basis from this file alone.
	#
	# A file with no receipt is deliberately legacy: its Hartree column is
	# interpreted by the historical raw-scalar rule below.  Partial/unknown
	# new schemas already refused inside sigma_output's one reader.
	#
	# The mixed legacy case is normal, not an edge case: a
	# ``sigma_mnk.h5`` written by an older run carries a non-zero ISDF
	# V_H, and pointing this CLI at a regenerated ``kin_ion.h5`` is
	# exactly how one re-derives QP energies without re-running Σ (Σ_xc
	# does not depend on V_H, so the rebuild is legitimate).
	# Double-counting ~500 eV of Hartree put the c606 sweep's QP gap at
	# −453 eV with rc=0 (job 7874840).
	#
	# Reading the attribute is the only supported discriminator — never
	# infer it from magnitudes (``file_io.kin_ion`` module docstring).
	# ``kin_ion_hartree_source`` / ``HARTREE_DATASET`` came in with the
	# kin_ion read above, which is the same lazy import for the same
	# reason.
	_src = kin_ion_hartree_source(kin_ion_path)
	vh_exact = None
	hartree_already_resolved = False
	receipt_c_at_dft = None
	if _receipt is not None:
		if (_receipt["band_start"], _receipt["band_stop"]) != (
				band_start, band_stop):
			raise ValueError(
				f"{os.path.basename(sigma_mnk_path)}'s EQP assembly receipt "
				f"covers [{_receipt['band_start']},{_receipt['band_stop']}) but "
				f"the QP rotations request [{band_start},{band_stop}).")
		expect_shape = (nk_irr, nb_window)
		if (_receipt["hartree_diag_ev"].shape != expect_shape
				or _receipt["sigma_x_diag_ev"].shape != expect_shape
				or _receipt["sigma_c_at_dft_diag_ev"].shape != expect_shape
				or _receipt["sigma_c_omega_diag_ev"].shape[1:] != expect_shape
				or _receipt["sigma_c_omega_diag_ev"].shape[0]
				!= omega_rel_ev.shape[0]):
			raise ValueError(
				f"{os.path.basename(sigma_mnk_path)}'s EQP assembly receipt has "
				f"H {_receipt['hartree_diag_ev'].shape}, X "
				f"{_receipt['sigma_x_diag_ev'].shape}, C(E_DFT) "
				f"{_receipt['sigma_c_at_dft_diag_ev'].shape}, C(omega) "
				f"{_receipt['sigma_c_omega_diag_ev'].shape}; expected file-wedge "
				f"shape {expect_shape}.")
		if not np.array_equal(
				_receipt["file_wedge_full_bz_rows"], kirr_to_kfull):
			raise ValueError(
				f"{os.path.basename(sigma_mnk_path)}'s EQP receipt names full-BZ "
				f"rows {_receipt['file_wedge_full_bz_rows'].tolist()}, but "
				f"{os.path.basename(qp_rotations_path)} requests file-wedge rows "
				f"{kirr_to_kfull.tolist()}; refusing a shape-compatible k-row "
				"permutation.  Shape alone is not a k-row identity proof.")
		if _receipt["hartree_source"] != _src:
			raise ValueError(
				f"EQP receipt Hartree source {_receipt['hartree_source']!r} "
				f"does not match {os.path.basename(kin_ion_path)} source {_src!r}; "
				"refusing to combine an assembled H from one source policy "
				"with a different mean-field artifact.")
		if bool(_receipt["kin_ion_has_hartree"]) != (_src == "folded"):
			raise ValueError(
				"EQP receipt and kin_ion disagree about whether scalar Hartree is "
				"folded into kin_ion.")
		hartree_diag = _receipt["hartree_diag_ev"]
		sigma_x_diag = _receipt["sigma_x_diag_ev"]
		receipt_c_at_dft = _receipt["sigma_c_at_dft_diag_ev"]
		# The receipt curve, not the raw operator diagonal, is the exact
		# dynamic assembly operand.  It was conditioned at every omega through
		# gw.degen_average before live assembly and therefore owns both C(E_DFT)
		# and Z for the reconstruction too.
		sigma_c_omega_diag = _receipt["sigma_c_omega_diag_ev"]
		hartree_already_resolved = True
		print(
			f"  EQP assembly receipt: assembled file-wedge H/X/C(E_DFT) "
			f"plus conditioned C(omega), "
			f"bases={_receipt['hartree_exchange_basis']}/"
			f"{_receipt['correlation_basis']}, "
			f"policy={_receipt['degeneracy_policy']}, "
			f"tol={_receipt['degeneracy_tol_ry']:.3e} Ry; C(E_DFT) and Z "
			"are re-derived together from that curve; raw operators remain "
			"untouched.")
	elif _src == "stored":
		vh_full = read_full_bz_dataset(kin_ion_path, HARTREE_DATASET)
		if vh_full.shape[1] < band_stop:
			raise ValueError(
				f"{HARTREE_DATASET} covers {vh_full.shape[1]} bands but the "
				f"sigma window needs {band_stop}.")
		vh_irr = vh_full[kirr_to_kfull, band_start:band_stop,
		                 band_start:band_stop]
		vh_exact = np.real(np.diagonal(vh_irr, axis1=1, axis2=2)) * RYD_TO_EV

	# From here on: zero independent semantics.  Same assembly (seam +
	# mean-field gate + Z-factor + Newton update), same formatter, as
	# ``gw_output.write_results``.  This CLI's whole remaining job is
	# "load artifacts, then call these two".
	assembly = assemble_eqp(
		kpoints_irr_frac=kpoints_irr,
		band_offset=band_start,
		e_dft_ev=e_dft_ev,
		kin_ion_diag_ev=kin_ion_diag_ev,
		hartree_diag_ev=np.real(hartree_diag),
		sigma_x_diag_ev=np.real(sigma_x_diag),
		sigma_c_omega_diag_ev=sigma_c_omega_diag,
		omega_rel_ev=omega_rel_ev,
		e_dft_rel_ev=e_dft_rel_ev,
		e_eval_ev=e_eval_ev,
		e_eval_rel_ev=e_eval_rel_ev,
		dE_ev=finite_difference_spacing_ev,
		nspin=1,
		hartree_source=_src,
		exact_hartree_diag_ev=vh_exact,
		hartree_already_resolved=hartree_already_resolved,
	)
	if (receipt_c_at_dft is not None
			and not np.array_equal(
				np.asarray(assembly.sigma_c_at_dft_diag_ev),
				np.asarray(receipt_c_at_dft))):
		raise ValueError(
			f"{os.path.basename(sigma_mnk_path)}'s persisted C(E_DFT) does not "
			"equal the shared assembler's value re-derived from the persisted "
			"conditioned C(omega) curve.")
	return assembly.write(eqp0_path=eqp0_path, eqp1_path=eqp1_path)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _build_parser() -> argparse.ArgumentParser:
	p = argparse.ArgumentParser(allow_abbrev=False,
		prog="python -m gw.eqp_bgw",
		description="Reproduce BGW eqp0.dat / eqp1.dat from a LORRAX gw_jax run.",
	)
	p.add_argument("run_dir", help="Run directory containing WFN.h5, kin_ion.h5, sigma_mnk.h5, qp_wfn_rotations.h5")
	p.add_argument("--wfn", default=None, help="Path to WFN.h5 (default: <run_dir>/WFN.h5)")
	p.add_argument("--kin-ion", default=None, help="Path to kin_ion.h5")
	p.add_argument("--sigma-mnk", default=None, help="Path to sigma_mnk.h5")
	p.add_argument("--qp-rotations", default=None, help="Path to qp_wfn_rotations.h5")
	p.add_argument(
		"--eval-energies", default=None,
		help="WFN_qp.h5 or qp_wfn_rotations.h5 holding the energies Sigma "
		     "was evaluated at, for the eqp1 linearization.  SELF-CONSISTENT "
		     "runs only — on a one-shot run those files hold eigh(H0+Sigma), "
		     "an output, and passing them centres eqp1 in the wrong place.  "
		     "Default: linearize at E_DFT (correct for one-shot)")
	p.add_argument("--eqp0", default="eqp0.dat", help="Output eqp0 filename (relative to run_dir unless absolute)")
	p.add_argument("--eqp1", default="eqp1.dat", help="Output eqp1 filename (relative to run_dir unless absolute)")
	p.add_argument(
		"--finite-difference-spacing",
		type=float, default=0.5,
		help="dE (eV) for the Z-factor central difference (BGW default 0.5)",
	)
	return p


def main(argv: Optional[list[str]] = None) -> int:
	args = _build_parser().parse_args(argv)
	eqp0_path, eqp1_path = make_eqp_bgw(
		args.run_dir,
		wfn_path=args.wfn,
		kin_ion_path=args.kin_ion,
		sigma_mnk_path=args.sigma_mnk,
		qp_rotations_path=args.qp_rotations,
		eval_energies_path=args.eval_energies,
		eqp0_out=args.eqp0,
		eqp1_out=args.eqp1,
		finite_difference_spacing_ev=args.finite_difference_spacing,
	)
	print(f"wrote: {eqp0_path}")
	print(f"wrote: {eqp1_path}")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
