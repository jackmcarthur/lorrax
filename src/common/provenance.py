"""Reproducibility metadata for human-readable LORRAX output files.

Every text-format writer in ``file_io.sigma_output`` and ``gw.eqp_bgw``
prepends ``provenance_header()`` so a stray ``eqp0.dat`` on disk months
from now still tells you which LORRAX version produced it.
"""
from __future__ import annotations

import datetime

#: Run-level identities a driver declares once (``set_run_provenance``) and
#: every output file repeats: one comment line each in the text headers, one
#: attribute each in ``sigma_mnk.h5``.  Today: ``four_current_carrier`` on a
#: bispinor GW run (``common.four_current_model``).
_RUN_PROVENANCE: dict[str, str] = {}


def set_run_provenance(**fields) -> None:
    """Replace the run-level identities; a ``None`` value is dropped.

    The GW driver calls this once after the deck resolves, unconditionally,
    so a second run in the same process never inherits the first's stamps.
    """
    _RUN_PROVENANCE.clear()
    _RUN_PROVENANCE.update(
        {str(k): str(v) for k, v in fields.items() if v is not None})


def run_provenance() -> dict[str, str]:
    """The identities :func:`set_run_provenance` declared (a copy)."""
    return dict(_RUN_PROVENANCE)


def lorrax_version() -> str:
    """Return the installed lorrax package version, or ``"unknown"``."""
    try:
        from importlib.metadata import version
        return version("lorrax")
    except Exception:
        return "unknown"


def provenance_header(*, comment: str = "#") -> str:
    """Return the comment lines stamping LORRAX version + UTC timestamp.

    One further line per run-level identity (:func:`set_run_provenance`).

    The comment marker defaults to ``#`` (works for ``.dat`` files and the
    BGW eqp{0,1}.dat parsers); pass ``comment="//"`` etc. for other formats.
    """
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%d %H:%M:%S UTC")
    return (f"{comment} Generated by LORRAX {lorrax_version()} at {stamp}\n"
            + "".join(f"{comment} {key} = {value}\n"
                      for key, value in _RUN_PROVENANCE.items()))
