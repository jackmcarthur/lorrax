def gauss_patterson(n: int) -> tuple[np.ndarray, np.ndarray]:
    """Return a fresh, ascending 31-, 63-, or 127-node rule."""
    try:
        x_positive, w_positive = _TABLES[int(n)]
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            f"Gauss--Patterson node count must be one of {tuple(_TABLES)}, "
            f"got {n!r}") from exc
    x_positive = np.asarray(x_positive, np.float64)
    w_positive = np.asarray(w_positive, np.float64)
    nodes = np.concatenate((-x_positive[:0:-1], x_positive))
    weights = np.concatenate((w_positive[:0:-1], w_positive))
    return nodes, weights


